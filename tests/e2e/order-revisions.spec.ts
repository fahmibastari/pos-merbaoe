import { expect, test } from "@playwright/test";
import { E2E_ADMIN_STATE, E2E_CASHIER_STATE, E2E_ADMIN_USERNAME, E2E_APPROVAL_PIN, E2E_PRODUCT_NAME } from "./constants";

test.use({ storageState: E2E_CASHIER_STATE });

test("Admin mengatur PIN; kasir menyimpan catatan, diskon persen dan Void ber-PIN", async ({ page, browser }) => {
  test.setTimeout(150_000);
  const iceNote = "less ice, tanpa gula tambahan; es hanya sedikit. ".repeat(4).slice(0, 150);
  const adminContext = await browser.newContext({ storageState: E2E_ADMIN_STATE });
  try {
    const admin = await adminContext.newPage();
    await admin.goto("/admin/users");
    await admin.getByRole("row").filter({ hasText: E2E_ADMIN_USERNAME }).getByRole("button", { name: "Atur PIN", exact: true }).click();
    const dialog = admin.getByRole("dialog");
    await dialog.getByLabel("PIN baru").fill(E2E_APPROVAL_PIN);
    await dialog.getByLabel("Konfirmasi PIN").fill(E2E_APPROVAL_PIN);
    await dialog.getByRole("button", { name: "Simpan PIN" }).click();
    await expect(dialog).not.toBeVisible();
    await expect(admin.getByText("PIN persetujuan Admin berhasil disimpan.")).toBeVisible();
  } finally { await adminContext.close(); }

  await page.setViewportSize({ width: 1180, height: 820 });
  await page.goto("/cashier");
  const search = page.getByLabel("Cari menu");
  await search.fill(E2E_PRODUCT_NAME);
  await search.press("Enter");
  const rows = page.locator("[data-cart-line]");
  await rows.first().locator("summary").click();
  await rows.first().getByLabel(`Catatan ${E2E_PRODUCT_NAME}`).fill("less sugar");
  await search.fill(E2E_PRODUCT_NAME);
  await search.press("Enter");
  await expect(rows).toHaveCount(2);
  await rows.last().locator("summary").click();
  await rows.last().getByLabel(`Catatan ${E2E_PRODUCT_NAME}`).fill(iceNote);
  await page.reload();
  await expect(rows).toHaveCount(2);
  await expect(rows.first().locator("summary")).toHaveText("less sugar");
  await expect(rows.last().locator("summary")).toHaveText(iceNote);
  const size = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
  expect(size.scroll).toBeLessThanOrEqual(size.width);
  await page.getByRole("button", { name: "QRIS", exact: true }).click();
  await page.getByLabel("Jenis diskon").selectOption("percentage");
  await page.getByLabel("Diskon (%)", { exact: true }).fill("10");
  await page.getByLabel("Persetujuan Admin").selectOption({ label: "E2E Administrator" });
  await page.getByLabel("PIN Admin", { exact: true }).fill("000000");
  await page.locator("#btn-checkout").click();
  await expect(page.getByRole("alert").filter({ hasText: "Persetujuan tidak valid" })).toBeVisible();
  await expect(rows).toHaveCount(2);
  await expect(page.getByLabel("PIN Admin", { exact: true })).toHaveValue("");
  await page.screenshot({ path: test.info().outputPath("pos-notes-tablet.png"), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath("pos-notes-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1180, height: 820 });
  await page.getByLabel("PIN Admin", { exact: true }).fill(E2E_APPROVAL_PIN);
  await page.locator("#btn-checkout").click();
  await expect(page.getByText("Transaksi berhasil", { exact: true })).toBeVisible();
  const href = await page.getByRole("link", { name: "Lihat & Cetak Struk" }).getAttribute("href");
  await page.getByRole("link", { name: "Lihat & Cetak Struk" }).click();
  await expect(page.getByText("less sugar", { exact: true })).toBeVisible();
  await expect(page.getByText(iceNote, { exact: true })).toBeVisible();
  await expect(page.getByText("Diskon (10%)", { exact: true })).toBeVisible();
  await page.goto(`${href}?paper=58`);
  await expect(page.getByText("less sugar", { exact: true })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  await expect(page.getByRole("article")).toBeVisible();
  expect(await page.getByRole("article").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath("receipt-notes-58mm.png"), fullPage: true });
  await page.emulateMedia({ media: "screen" });
  const invoice = await page.locator("dd").first().innerText();
  await page.goto(`/cashier/history?q=${encodeURIComponent(invoice)}`);
  const sale = page.getByRole("row").filter({ hasText: invoice });
  await expect(sale).toContainText("less sugar");
  await sale.getByRole("button", { name: "Void", exact: true }).click();
  const voidDialog = page.getByRole("dialog");
  await voidDialog.getByLabel("Alasan pembatalan").fill("Uji catatan dan diskon");
  await voidDialog.getByLabel("Persetujuan Admin").selectOption({ label: "E2E Administrator" });
  await voidDialog.getByLabel("PIN Admin", { exact: true }).fill(E2E_APPROVAL_PIN);
  await voidDialog.getByRole("button", { name: "Ya, batalkan transaksi" }).click();
  await expect(voidDialog).not.toBeVisible();
  await expect(sale).toContainText("Dibatalkan");
  await page.goto(href!);
  await expect(page.getByText("TRANSAKSI DIBATALKAN", { exact: true })).toBeVisible();
});
